#!/usr/bin/env python3
"""Generate descriptive local reviewer observations from archived records."""
import argparse,hashlib,json,statistics
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'internal_tests/2026-11-12-local-agent/records.json'
out=root/'web/downloads/blueprintbench/local-agent-diagnostics.json'
base='https://github.com/sev7enITA/PALO-BlueprintBench/tree/main/internal_tests/2026-11-12-local-agent/'
def median(vals):return round(statistics.median(vals),3) if vals else None
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
 data=json.loads(source.read_text(encoding='utf-8'));assert data['qualification'] is False
 runs=[]
 for run in data['runs']:
  assert type(run.get('is_replay')) is bool, 'Every run must explicitly identify replays'
  info={k:v for k,v in run.items() if k!='observations'};info['cases']=[]
  for case in dict.fromkeys(x['case_id'] for x in run['observations']):
   group=[x for x in run['observations'] if x['case_id']==case]
   for row in group:
    for name in ('request','response'):
     f=row.get(name)
     if f:
      path=(source.parent/f['path']).resolve();assert path.is_relative_to(source.parent.resolve())
      assert hashlib.sha256(path.read_bytes()).hexdigest()==f['sha256']
   complete=[x for x in group if x['finish_reason']=='stop']
   valid=[x for x in complete if x['status'] in ('advisory_contract_valid','posthoc_contract_valid')]
   times=[x['elapsed_seconds'] for x in complete if isinstance(x.get('elapsed_seconds'),(int,float))]
   tokens=[x['completion_tokens'] for x in complete if isinstance(x.get('completion_tokens'),(int,float))]
   if run['is_replay']:tokens=[]  # No additional tokens were generated by the replay.
   caps={x['output_cap_tokens'] for x in group if x.get('output_cap_tokens') is not None};prompts={x['prompt_version'] for x in group if x.get('prompt_version') is not None}
   ref={x['reference_label'] for x in group if x.get('reference_label')};labels=sorted({x['label'] for x in valid if x.get('label')})
   timedout=[x for x in group if x.get('status')=='stopped' and 'timed out' in (x.get('reason') or '').lower()]
   timeout_seconds=600 if timedout and all(599 <= x.get('elapsed_seconds',0) <= 601 for x in timedout) else None
   name=group[0]['case_name']+(' (timeout at 600 s)' if timeout_seconds==600 else '')
   info['cases'].append({'case_id':case,'case_name':name,'assigned':len(group),'completed':len(complete),'contract_valid':len(valid),'timeout_count':len(timedout),'timeout_seconds':timeout_seconds,'median_seconds':median(times),'median_completion_tokens':median(tokens),'labels':labels,'reference_label':next(iter(ref)) if len(ref)==1 else None,'agreement_count':sum(x['label']==x['reference_label'] for x in valid) if valid else None,'output_cap_tokens':next(iter(caps)) if len(caps)==1 else None,'prompt_version':next(iter(prompts)) if len(prompts)==1 else None,'evidence_url':base+'raw/'+run['id']})
  runs.append(info)
 result={'title':'Local advisory challenge agent diagnostics','date':data['date'],'status':data['status'],'summary':data['description'],'limitations':data['limitations'],'runs':runs}
 raw=(json.dumps(result,indent=2,ensure_ascii=False)+'\n').encode()
 if args.check:
  if not out.exists() or out.read_bytes()!=raw:raise SystemExit('Local agent diagnostics data mismatch')
 else:out.parent.mkdir(parents=True,exist_ok=True);out.write_bytes(raw)
 print('local agent diagnostics: '+('verified' if args.check else 'built'))
if __name__=='__main__':main()
